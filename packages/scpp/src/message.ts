import { createHash } from "node:crypto";

import { ScppError } from "./errors.js";
import {
  SCPP_RESERVED_TAGS,
  SCPP_TAGS,
  SCPP_V2_FIELD_CODECS,
  SCPP_V2_FIELD_ORDER,
  SCPP_VERSION_V2,
  type ScppFieldName,
} from "./profile.js";
import { decodeTlv, encodeTlv, type TlvField } from "./tlv.js";

/* The version is not an input. A v2 message is v2, and accepting the version
   from the caller would create a second way to say the same thing and a way to
   sign a message the encoder did not produce. It is emitted from the profile
   constant and appears on the decoded message. */
export interface ScppV2MessageInput {
  readonly amountAtomic: string;
  readonly assetSymbol: string;
  readonly transactionDate: string;
  readonly transactionTime: string;
  readonly deviceId: string;
  readonly receivingAccountId: string;
  readonly counter: number;
  /* Eight hexadecimal characters, generated by the reader for this one tap. */
  readonly unpredictableNumber: string;
  readonly paymentId: string;
}

export interface ScppV2Message extends ScppV2MessageInput {
  readonly version: number;
}

const INPUT_FIELDS: readonly ScppFieldName[] = SCPP_V2_FIELD_ORDER.filter((name) => name !== "version");

/* Rejected by name rather than falling through to "unknown field", because
   every one of these is something somebody could reasonably expect to be
   carried -- from cardplan, from EMV, or from a later version of this profile
   -- and a caller who sends one deserves to be told why it is not carried
   rather than that it was not recognised. The reserved tags come from the
   profile so the two lists cannot drift apart. */
const RESERVED_INPUT_KEYS = new Map<string, string>([
  ["version", "is emitted from the profile and is not accepted from the caller"],
  [
    "nonce",
    "was the v1 server nonce and is not carried by SCPP v2: the freshness value is now unpredictableNumber, which the reader generates itself",
  ],
  [
    "actionId",
    "was a v1 field and is not carried by SCPP v2: paymentId already names the payment session being approved",
  ],
  [
    "expiry",
    "was a v1 field and is not carried by SCPP v2: the authorisation window is the server's and is checked there, not signed by the reader",
  ],
  ["pinCommitment", "is reserved for a later profile and is not carried by SCPP v2"],
  [
    "currencyNumeric",
    "is reserved: a Stableyard payment is denominated in an asset, carried in assetSymbol, not in a fiat currency",
  ],
  ...Object.values(SCPP_RESERVED_TAGS).map(
    ({ tag, reason }) => [tag, `is ${reason}, and is not carried by SCPP v2`] as const,
  ),
]);

function assertInputShape(input: unknown): Record<string, unknown> {
  if (typeof input !== "object" || input === null || Array.isArray(input)) {
    throw new ScppError("SCPP_INVALID_FIELD", "an SCPP message must be an object");
  }
  const record = input as Record<string, unknown>;
  const allowed = new Set<string>(INPUT_FIELDS);
  for (const key of Object.keys(record)) {
    const reserved = RESERVED_INPUT_KEYS.get(key);
    if (reserved !== undefined) {
      throw new ScppError("SCPP_RESERVED_TAG", `${key} ${reserved}`, key);
    }
    if (!allowed.has(key)) {
      throw new ScppError("SCPP_UNKNOWN_FIELD", `${key} is not a field of SCPP v2`, key);
    }
  }
  for (const name of INPUT_FIELDS) {
    if (!(name in record)) {
      throw new ScppError("SCPP_MISSING_FIELD", `${name} is required and the profile has no optional fields`, name);
    }
  }
  return record;
}

export function buildScppV2Message(input: ScppV2MessageInput): ScppV2Message {
  const record = assertInputShape(input);
  const message: Record<string, unknown> = { version: SCPP_VERSION_V2 };
  for (const name of INPUT_FIELDS) {
    const codec = SCPP_V2_FIELD_CODECS[name];
    message[name] = codec.decode(codec.encode(record[name]));
  }
  return Object.freeze(message) as unknown as ScppV2Message;
}

export function scppV2Fields(input: ScppV2MessageInput): TlvField[] {
  const record = assertInputShape(input);
  return SCPP_V2_FIELD_ORDER.map((name) => {
    const codec = SCPP_V2_FIELD_CODECS[name];
    const value = name === "version" ? SCPP_VERSION_V2 : record[name];
    return { tag: codec.tag, value: codec.encode(value) };
  });
}

export function encodeScppV2Message(input: ScppV2MessageInput): Uint8Array {
  return encodeTlv(scppV2Fields(input));
}

/* The challenge is what the card signs, and the only thing the card ever sees
   of the payment. It is the hash of the encoded bytes, never of a re-serialised
   object, so a reader and the server agree by producing identical bytes rather
   than by agreeing on a serialisation. */
export function scppV2Challenge(input: ScppV2MessageInput): Uint8Array {
  return sha256(encodeScppV2Message(input));
}

export function sha256(bytes: Uint8Array): Uint8Array {
  if (!(bytes instanceof Uint8Array)) {
    throw new ScppError("SCPP_INVALID_FIELD", "sha256 takes a Uint8Array");
  }
  return new Uint8Array(createHash("sha256").update(bytes).digest());
}

export function decodeScppV2Message(bytes: Uint8Array): ScppV2Message {
  const fields = decodeTlv(bytes);
  if (fields.length !== SCPP_V2_FIELD_ORDER.length) {
    throw new ScppError(
      "SCPP_MALFORMED_TLV",
      `an SCPP v2 message carries exactly ${SCPP_V2_FIELD_ORDER.length} fields and this one carries ${fields.length}`,
    );
  }
  const message: Record<string, unknown> = {};
  SCPP_V2_FIELD_ORDER.forEach((name, index) => {
    const field = fields[index] as TlvField;
    const codec = SCPP_V2_FIELD_CODECS[name];
    if (field.tag !== codec.tag) {
      throw new ScppError(
        "SCPP_MALFORMED_TLV",
        `expected ${codec.tag} (${name}) at position ${index} and found ${field.tag}; the field order is part of the profile`,
      );
    }
    message[name] = codec.decode(field.value);
  });
  if (message.version !== SCPP_VERSION_V2) {
    throw new ScppError("SCPP_INVALID_FIELD", `${SCPP_TAGS.version} carries version ${String(message.version)} and this decoder speaks v2`, "version");
  }
  return Object.freeze(message) as unknown as ScppV2Message;
}
